/// Простая локализация: оборачиваем русские строки в [t]. Если выбран
/// кыргызский и перевод есть — возвращаем его, иначе русский (мягкий откат).
/// Так новые строки переводятся добавлением записи в [_ky], без ключей.
library;

enum Lang {
  ru('Русский'),
  ky('Кыргызча');

  final String label;
  const Lang(this.label);
}

/// Текущий язык (глобально; меняется из настроек, экраны перерисовываются
/// через AppState.notifyListeners).
Lang appLang = Lang.ru;

/// Перевод русской строки на текущий язык.
String t(String ru) => appLang == Lang.ky ? (_ky[ru] ?? ru) : ru;

/// Число со словом в нужном числе: `plural(7, 'аят', 'аята', 'аятов')`.
///
/// В кыргызском счётное слово не изменяется («7 аят»), поэтому там всегда
/// берётся [one] — точнее, его кыргызский перевод через [t].
///
/// Нужен, чтобы не писать «7 аят(ов)»: скобочные окончания читаются как
/// машинный вывод, а не как текст, написанный человеком.
/// Глагол в роде говорящего: «прочитал» / «прочитала».
///
/// Пол лежит в профиле, так что писать «прочитал(а)» незачем — скобки
/// читаются как бланк, а не как обращение к человеку. В кыргызском рода у
/// глагола нет, поэтому там берётся перевод [ru] как есть.
String gendered(String ru, String male, String female, bool isFemale) =>
    appLang == Lang.ky ? t(ru) : (isFemale ? female : male);

String plural(int n, String one, String few, String many) {
  if (appLang == Lang.ky) return '$n ${t(one)}';
  final mod100 = n.abs() % 100;
  final mod10 = n.abs() % 10;
  final word = (mod100 >= 11 && mod100 <= 14)
      ? many
      : mod10 == 1
          ? one
          : (mod10 >= 2 && mod10 <= 4)
              ? few
              : many;
  return '$n $word';
}

