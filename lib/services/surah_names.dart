/// Название суры кириллицей; на неизвестном номере — как отдаёт пакет.
String surahName(int n) =>
    (n >= 1 && n <= surahNamesRu.length) ? surahNamesRu[n - 1] : quran.getSurahName(n);

/// Латинское написание из пакета — нужно поиску: часть людей набирает
/// «al-baqara» латиницей, особенно если пришла из другого приложения.
String surahNameLatin(int n) => quran.getSurahName(n);

/// «7 аятов» / «2 аята» — вместо прежнего «7 аят».
String verseCountLabel(int n) => plural(n, 'аят', 'аята', 'аятов');
