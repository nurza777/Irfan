#!/bin/sh
# Вызывается MediaMTX (runOnReady) при старте публикации эфира.
# Боевая копия лежит на сервере: /opt/irfan-server/live-on.sh
#
# Что делает: берёт один поток с телефона устаза (480p, 30 fps, 1200 кбит/с)
# и раскладывает его в четыре качества + master.m3u8, чтобы плеер сам
# выбирал посильное. Затем публикует адрес потока в status.json.
#
# ЛЕСТНИЦА КАЧЕСТВ подобрана под реальный канал, а не под красивые цифры.
# Замеры 01.09.2026 (Бишкек → Hetzner Nuremberg): пропускная способность
# гуляет от 38 до 900 КБ/с на одном и том же файле в пределах минуты.
# Поэтому нижняя ступень сделана 200k видео + 48k звука ≈ 31 КБ/с — она
# пролезает даже в самый глубокий провал. Без неё в провале не открывался
# ни один вариант, и эфир просто вставал.
#
# ДЛИНА СЕГМЕНТА 4 с (была 2 с) и список из 10 штук: плееру есть чем
# пережить провал канала. Плата — задержка эфира растёт примерно вдвое,
# секунд до десяти-двенадцати. Для урока это приемлемо, для разговора
# в прямом эфире было бы нет. Задержка ДО ПЕРВОЙ КАРТИНКИ при этом
# не пострадала: замер 01.09.2026 — 8 секунд от начала публикации.
TITLE="Прямой эфир устаза"
if [ -s /opt/irfan-server/api/live-title.txt ]; then
  TITLE=$(head -c 200 /opt/irfan-server/api/live-title.txt | tr -d "\"" | tr -d "\n")
fi
mkdir -p /opt/irfan-server/api/hls /opt/irfan-server/logs
rm -f /opt/irfan-server/api/hls/* /opt/irfan-server/hls.stop

# Откуда брать поток. Ключ эфира в скрипте НЕ пишем: репозиторий публичный,
# а ключ — это право выйти в эфир от имени устаза. MediaMTX сам передаёт
# хуку runOnReady путь готового потока в MTX_PATH («live/<ключ>»); если
# скрипт запустили руками, берём ключ оттуда же, где его держит apiserver.
SRC_PATH="$MTX_PATH"
if [ -z "$SRC_PATH" ]; then
  SRC_PATH="live/$(python3 -c 'import json; print(json.load(open("/etc/irfan/stream.json")).get("key", ""))' 2>/dev/null)"
fi

# ── Чат ───────────────────────────────────────────────────────────────────
#
# Раньше переписка стиралась при КАЖДОМ запуске. Пока приложение устаза не
# умело переподключаться, это было почти незаметно; теперь оно возвращается
# само после обрыва, и безусловная очистка уносила бы чат при каждом провале
# связи. Поэтому чистим, только если прошлый эфир закончился давно, — иначе
# считаем, что это та же трансляция, просто прерванная.
NOW=$(date +%s)
LAST_END=0
if [ -s /opt/irfan-server/last-live-end ]; then
  LAST_END=$(cat /opt/irfan-server/last-live-end)
fi
if [ $((NOW - LAST_END)) -gt 600 ]; then
  echo "[]" > /opt/irfan-server/api/comments.json
fi

# ── Отметки для сводки ────────────────────────────────────────────────────
#
# Запоминаем начало и текущую длину access-лога nginx. По разнице live-off.sh
# посчитает, сколько было зрителей: разбирать даты в формате nginx из shell
# мучительно, а смещение по строкам надёжно и дёшево.
echo "$NOW" > /opt/irfan-server/live-start
# Обнуляем пик зрителей: он считается apiserver-ом в памяти и должен
# относиться к ЭТОЙ трансляции, а не копиться от всех предыдущих.
curl -s -m 5 "http://127.0.0.1:8090/live/viewers?reset=1" > /dev/null 2>&1 || true
wc -l < /var/log/nginx/access.log > /opt/irfan-server/live-logmark 2>/dev/null \
  || echo 0 > /opt/irfan-server/live-logmark
# Лог транскода начинаем заново: так число перезапусков в сводке относится
# к этому эфиру, а не ко всем предыдущим. История эфиров не теряется —
# она копится в logs/live-history.log.
: > /opt/irfan-server/logs/ffmpeg.log

# ── Присмотр за транскодом ────────────────────────────────────────────────
#
# Проверено опытом 01.09.2026: если ffmpeg умирает посреди эфира, а телефон
# продолжает публиковать, MediaMTX молчит — для него поток по-прежнему
# «готов», и runOnNotReady не срабатывает. В результате status.json остаётся
# live:true, master.m3u8 отдаётся с кодом 200, но плейлисты не обновляются.
# Ученик замерзает навсегда: сторож в приложении переоткрывает поток, снова
# получает мёртвый плейлист и снова замерзает. Восстановить это мог только
# устаз, вручную перезапустив эфир.
#
# Поэтому транскод запускается в цикле с перезапуском. Выход из цикла:
# либо появился файл-флаг hls.stop (его ставит live-off.sh при штатном
# завершении), либо ffmpeg пять раз подряд не смог подключиться к источнику —
# значит публикации больше нет.
(
  tries=0
  while [ "$tries" -lt 5 ]; do
    [ -f /opt/irfan-server/hls.stop ] && break

    # Метка времени старта в имени сегмента. Нужна из-за кэша на CDN: без неё
    # у каждой трансляции сегменты назывались бы одинаково (s_0_00001.ts), и
    # новый эфир, начатый вскоре после старого, отдавал бы зрителям куски
    # предыдущего. По той же причине метка обновляется при КАЖДОМ
    # перезапуске транскода, а не один раз на эфир.
    STAMP=$(date +%s)
    START=$(date +%s)

    # Опорные кадры принудительно раз в 4 с ПО ВРЕМЕНИ, а не раз в N кадров.
    # Так границы сегментов совпадают у всех четырёх качеств и совпадают с
    # заданной длиной: при фиксированном -g сегменты «съезжали» бы, если
    # телефон отдаёт не ровно 30 fps, и переключение качества давало бы рывок.
    #
    # hls_delete_threshold: держим на диске пять сегментов сверх плейлиста.
    # Ученик на слабом канале отстаёт от живого края, и без запаса нужный
    # ему сегмент уже удалён — плеер получает 404 и рвёт воспроизведение.
    ffmpeg -hide_banner -loglevel warning -fflags nobuffer \
      -i "rtmp://127.0.0.1:1935/$SRC_PATH" \
      -filter_complex "[0:v]split=4[a][b][c][d];[a]scale=-2:480[v0];[b]scale=-2:360[v1];[c]scale=-2:240[v2];[d]scale=-2:180[v3]" \
      -map "[v0]" -map "[v1]" -map "[v2]" -map "[v3]" \
      -map 0:a -map 0:a -map 0:a -map 0:a \
      -c:v libx264 -preset veryfast -sc_threshold 0 \
      -force_key_frames:v "expr:gte(t,n_forced*4)" \
      -b:v:0 1200k -maxrate:v:0 1400k -bufsize:v:0 2400k \
      -b:v:1 700k  -maxrate:v:1 800k  -bufsize:v:1 1400k \
      -b:v:2 400k  -maxrate:v:2 450k  -bufsize:v:2 800k \
      -b:v:3 200k  -maxrate:v:3 230k  -bufsize:v:3 400k \
      -c:a aac -ac 2 -b:a:0 96k -b:a:1 96k -b:a:2 64k -b:a:3 48k \
      -f hls -hls_time 4 -hls_list_size 10 -hls_delete_threshold 5 \
      -hls_flags delete_segments+independent_segments \
      -hls_segment_type mpegts \
      -hls_segment_filename "/opt/irfan-server/api/hls/s_${STAMP}_%v_%05d.ts" \
      -master_pl_name master.m3u8 \
      -var_stream_map "v:0,a:0 v:1,a:1 v:2,a:2 v:3,a:3" \
      /opt/irfan-server/api/hls/stream_%v.m3u8 \
      >> /opt/irfan-server/logs/ffmpeg.log 2>&1

    [ -f /opt/irfan-server/hls.stop ] && break

    # Продержался дольше 20 с — значит источник живой, а упали по случайности:
    # счётчик попыток обнуляем, иначе за долгий эфир он исчерпался бы.
    if [ $(( $(date +%s) - START )) -gt 20 ]; then
      tries=0
    else
      tries=$((tries + 1))
    fi
    echo "$(date '+%F %T') транскод упал, перезапуск (попытка $tries)" \
      >> /opt/irfan-server/logs/ffmpeg.log
    sleep 2
  done
) &
echo $! > /opt/irfan-server/hls.pid

# ── Публикация статуса ученикам ───────────────────────────────────────────
#
# Раньше status.json выставлялся в live:true БЕЗУСЛОВНО — даже если ждать
# master.m3u8 надоело по таймауту. То есть при неудачном старте транскода
# ученики видели «эфир идёт», а плеер получал 404 и бесконечно ошибался.
# Теперь статус публикуется, только если плейлист действительно появился.
(
  i=0
  while [ $i -lt 120 ]; do
    [ -f /opt/irfan-server/api/hls/master.m3u8 ] && break
    i=$((i + 1)); sleep 0.5
  done
  if [ -f /opt/irfan-server/api/hls/master.m3u8 ]; then
    cat > /opt/irfan-server/api/status.json <<JSON
{"live": true, "title": "$TITLE", "url": "https://api.irfan.kg/hls/master.m3u8"}
JSON
    # Уведомляем учеников — ПОСЛЕ публикации статуса, а не до: человек
    # нажмёт на уведомление сразу, и эфир к этому моменту должен уже
    # отдаваться, иначе он попадёт на «Сейчас эфира нет».
    # Без настроенного APNs скрипт просто ничего не делает.
    python3 /opt/irfan-server/push.py "Начался прямой эфир" "$TITLE" \
      >> /opt/irfan-server/logs/push.log 2>&1 || true
  else
    echo "$(date '+%F %T') транскод не поднялся за 60 с — статус не публикуем" \
      >> /opt/irfan-server/logs/ffmpeg.log
  fi
) &
